#!/usr/bin/env node
// Writes docs/voice-phrases.md: the checklist for recording (or generating) the spoken directions.
// Run: npm run voice:list
import { writeFile } from 'node:fs/promises';
import { PHRASES, PHRASE_KEYS, SPOKEN_DISTANCES_M, renderPhrase } from '../src/core/phrases.ts';

const rows = PHRASE_KEYS.map((k) => `| \`${k}\` | ${PHRASES[k].en} | ${PHRASES[k].ur} | ${PHRASES[k].pa} |`);
const dist = SPOKEN_DISTANCES_M.map((m) => `| \`d${m}\` | ${renderPhrase('straight', 'en', m).replace(PHRASES.straight.en, '').trim()} | ${renderPhrase('straight', 'ur', m).replace(PHRASES.straight.ur, '').trim()} | ${renderPhrase('straight', 'pa', m).replace(PHRASES.straight.pa, '').trim()} |`);

const md = `# Spoken directions: recording checklist

Generated by \`npm run voice:list\` from \`src/core/phrases.ts\`. Do not edit by hand.

**The Urdu and Punjabi wording is a DRAFT. A native speaker must review it before release.** Wrong or unnatural
directions while driving are a safety problem. Punjabi is Shahmukhi (Arabic script), as used in Pakistan.

## How recordings work
1. Record each row below once per language: a short, clear clip of just that text, same voice and volume throughout.
2. Save as \`public/audio/<lang>/<key>.mp3\` (lang = \`en\`, \`ur\` or \`pa\`), e.g. \`public/audio/ur/turn-left.mp3\`.
3. List the keys you have in \`public/audio/manifest.json\`, e.g. \`{ "ur": ["d500", "d200", "turn-left"] }\`.
4. The app plays recordings only when every clip a sentence needs exists (distance + phrase); otherwise it uses the
   phone's text-to-speech voice. It never mixes a recording and a synthetic voice inside one sentence.

A distance prefix is played first ("In 500 meters" then "Turn left"), so the \`d500\` / \`d200\` clips must read naturally
before any phrase.

## Distance prefixes (${SPOKEN_DISTANCES_M.length} clips per language)
| Key | English | اردو | پنجابی |
|---|---|---|---|
${dist.join('\n')}

## Phrases (${PHRASE_KEYS.length} clips per language)
| Key | English | اردو | پنجابی |
|---|---|---|---|
${rows.join('\n')}

Street names are not recorded: they stay on screen (and are spoken in English only by the phone's voice).
`;
await writeFile(new URL('../docs/voice-phrases.md', import.meta.url), md);
console.log(`wrote docs/voice-phrases.md (${PHRASE_KEYS.length + SPOKEN_DISTANCES_M.length} clips per language)`);
